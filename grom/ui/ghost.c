static uint32_t pixels[GHOST_W * GHOST_H];
static lv_image_dsc_t image;

const lv_image_dsc_t *grom_ghost_image(void) {
    if(image.data) return &image;

    uint8_t source[GHOST_SOURCE_W * GHOST_SOURCE_H];
    size_t out = 0;
    for(size_t i = 0; i < sizeof(runs); i += 2) {
        size_t count = runs[i];
        if(runs[i + 1] >= sizeof(palette) / sizeof(palette[0]) ||
           count > sizeof(source) - out) return NULL;
        memset(source + out, runs[i + 1], count);
        out += count;
    }
    if(out != sizeof(source)) return NULL;

    for(size_t y = 0; y < GHOST_H; y++) {
        size_t source_y = y * GHOST_SOURCE_H / GHOST_H;
        for(size_t x = 0; x < GHOST_W; x++) {
            size_t source_x = x * GHOST_SOURCE_W / GHOST_W;
            pixels[y * GHOST_W + x] =
                palette[source[source_y * GHOST_SOURCE_W + source_x]];
        }
    }

    image.header.magic = LV_IMAGE_HEADER_MAGIC;
    image.header.cf = LV_COLOR_FORMAT_ARGB8888;
    image.header.w = GHOST_W;
    image.header.h = GHOST_H;
    image.header.stride = GHOST_W * 4;
    image.data_size = sizeof(pixels);
    image.data = (const uint8_t *)pixels;
    return &image;
}
